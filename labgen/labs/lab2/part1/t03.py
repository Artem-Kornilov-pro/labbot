IN = MatrixArray("F", "Q")

C_SOLVE = f'''    /* для каждого столбца: произведение элементов и поиск его в массиве Q */
    cnt = 0;
    for (j = 1; j <= m; j++){{
        pr = 1;
        i = 1;
        while (i <= n && pr != 0){{        /* досрочный выход: при нуле pr уже 0 */
            pr = pr * F[i][j];
            i++;
        }}
        {c_find("Q", "k", "pr")}
        if (t <= k){{                      /* совпадение есть - сортируем столбец */
            cnt++;
            col[cnt] = j;
{c_sort_col("F", "j", "n")}
        }}
    }}

    if (cnt == 0)
        printf("\\nПроизведение ни одного столбца не совпадает с элементами Q - "
               "матрица не изменилась.\\n");
    else{{
{c_print_list("Упорядочены по возрастанию столбцы: ", "col", "cnt")}
{c_print_mat("F", "n", "m", "Преобразованная матрица F:")}
    }}
'''


def simulate(con):
    n, m_, Fm, k, Q = IN.read(con)
    con.begin_results()
    cols = []
    for j in range(1, m_ + 1):
        pr, i = 1, 1
        while i <= n and pr != 0:
            pr *= Fm[i][j]
            i += 1
        if py_find(Q, k, pr) <= k:
            cols.append(j)
            py_sort_col(Fm, j, n)
    if not cols:
        con.printf("\nПроизведение ни одного столбца не совпадает с элементами Q - матрица не изменилась.\n")
    else:
        py_print_list(con, "Упорядочены по возрастанию столбцы: ", cols)
        py_print_mat(con, Fm, n, m_, "Преобразованная матрица F:")


def svyaz(rep):
    rep.fline("1. ", F("∀ j = {1..m}:  pr[j] = ") + nprod(m("i = 1"), m("n"), m("F[i, j]")))
    rep.fline("2. ", F("∀ j = {1..m}:  (∃ t ∈ [1:k]: Q[t] = pr[j])  ⇒"))
    rep.fline("", F("⇒  ∀ i = {1..n − 1}:  F'[i, j] ≤ F'[i + 1, j],"), indent=0.6)
    rep.para("где F'[1:n, j] – тот же набор элементов столбца j, переставленный по возрастанию.", indent=0.6)


