IN = TwoMatrices()

C_SOLVE = f'''    /* матрица C[1:p, 1:q], p = max(n, x), q = max(m, y) */
    p = n > x ? n : x;
    q = m > y ? m : y;
    for (i = 1; i <= p; i++)
        for (j = 1; j <= q; j++){{
            C[i][j] = 0;
            if (i <= n && j <= m) C[i][j] = C[i][j] + A[i][j];
            if (i <= x && j <= y) C[i][j] = C[i][j] + B[i][j];
        }}
{c_print_mat("C", "p", "q", "Матрица C:", ind="    ")}

    /* максимальный элемент C и его поиск в первом столбце A */
    mx = C[1][1];
    for (i = 1; i <= p; i++)
        for (j = 1; j <= q; j++)
            if (C[i][j] > mx) mx = C[i][j];
    i = 1;
    while (i <= n && A[i][1] != mx)     /* досрочный выход при совпадении */
        i++;

    if (i > n)
        printf("\\nМаксимальный элемент C (%d) не совпадает ни с одним элементом "
               "первого столбца A - матрица C не изменилась.\\n", mx);
    else{{
        cnt = 0;
        for (i = 1; i <= p; i++)
            for (j = 1; j <= q; j++)
                if (C[i][j] == mx){{
                    C[i][j] = 0;
                    cnt++;
                }}
        printf("\\nМаксимальный элемент C (%d) есть в первом столбце A - "
               "обнулено элементов: %d.\\n", mx, cnt);
{c_print_mat("C", "p", "q", "Преобразованная матрица C:")}
    }}
'''


def simulate(con):
    n, m, A, x, y, B = IN.read(con)
    con.begin_results()
    p, q = max(n, x), max(m, y)
    C = [[0] * (q + 1) for _ in range(p + 1)]
    for i in range(1, p + 1):
        for j in range(1, q + 1):
            if i <= n and j <= m:
                C[i][j] += A[i][j]
            if i <= x and j <= y:
                C[i][j] += B[i][j]
    py_print_mat(con, C, p, q, "Матрица C:")
    mx = max(C[i][j] for i in range(1, p + 1) for j in range(1, q + 1))
    if all(A[i][1] != mx for i in range(1, n + 1)):
        con.printf("\nМаксимальный элемент C (%d) не совпадает ни с одним элементом первого столбца A - "
                   "матрица C не изменилась.\n" % mx)
    else:
        cnt = 0
        for i in range(1, p + 1):
            for j in range(1, q + 1):
                if C[i][j] == mx:
                    C[i][j] = 0
                    cnt += 1
        con.printf("\nМаксимальный элемент C (%d) есть в первом столбце A - обнулено элементов: %d.\n" % (mx, cnt))
        py_print_mat(con, C, p, q, "Преобразованная матрица C:")


def svyaz(rep):
    rep.fline("1. ", F("p = max(n, x),  q = max(m, y);  ∀ i = {1..p}, ∀ j = {1..q}:"))
    rep.para("C[i, j] = A[i, j] + B[i, j], если A[i, j] и B[i, j] существуют; C[i, j] = A[i, j], если существует "
             "только A[i, j]; C[i, j] = B[i, j], если существует только B[i, j]; C[i, j] = 0, если не существуют "
             "оба;", indent=0.6, align=None)
    rep.fline("2. ", F("mx = max C[i, j],  i = {1..p},  j = {1..q}"))
    rep.fline("3. ", F("(∃ i ∈ [1:n]: A[i, 1] = mx)  ⇒  ∀ C[i, j] = mx:  C'[i, j] = 0"))


