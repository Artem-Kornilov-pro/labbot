IN = MatrixArray("Z", "P")

C_SOLVE = f'''    /* удаление путём сдвига столбцов, все элементы которых отсутствуют в P */
    q = 0;                              /* число оставшихся столбцов */
    for (j = 1; j <= m; j++){{
        found = 0;
        i = 1;
        while (i <= n && !found){{          /* досрочный выход: найден элемент из P */
            t = 1;
            while (t <= k && P[t] != Z[i][j])  /* досрочный выход при совпадении */
                t++;
            if (t <= k) found = 1;
            i++;
        }}
        if (found){{                        /* есть элемент из P - остаётся */
            q++;
            if (q != j)
                for (t = 1; t <= n; t++)
                    Z[t][q] = Z[t][j];
        }}
    }}

    if (q == 0)
        printf("\\nНи один элемент матрицы не встречается в P - удалены все столбцы, "
               "матрица пуста.\\n");
    else if (q == m)
        printf("\\nВ каждом столбце есть элемент из P - удалений не было, "
               "матрица не изменилась.\\n");
    else{{
        printf("\\nУдалено столбцов: %d.\\n", m - q);
{c_print_mat("Z", "n", "q", "Преобразованная матрица Z:")}
    }}
'''


def simulate(con):
    n, m, Z, k, P = IN.read(con)
    con.begin_results()
    q = 0
    for j in range(1, m + 1):
        if any(py_find(P, k, Z[i][j]) <= k for i in range(1, n + 1)):
            q += 1
            for t in range(1, n + 1):
                Z[t][q] = Z[t][j]
    if q == 0:
        con.printf("\nНи один элемент матрицы не встречается в P - удалены все столбцы, матрица пуста.\n")
    elif q == m:
        con.printf("\nВ каждом столбце есть элемент из P - удалений не было, матрица не изменилась.\n")
    else:
        con.printf("\nУдалено столбцов: %d.\n" % (m - q))
        py_print_mat(con, Z, n, q, "Преобразованная матрица Z:")


def svyaz(rep):
    rep.fline("", F("∀ j = {1..m}:  столбец j удаляется  ⇔  ∀ i = {1..n}, ∀ t = {1..k}: P[t] ≠ Z[i, j]"))
    rep.fline("", F("Z'[1:n, 1:q] – оставшиеся столбцы в прежнем порядке"))


