def _t(mat, case):
    return Test(IN.lines(mat), IN.shown(mat), case)


TESTS = [
    _t([[1, 0, 3, 4], [5, 6, 7, 0], [2, 8, 9, 1]], "Удалены столбцы 1 и 3 (без нулей), остальные сдвинуты"),
    _t([[1, 2], [3, 4]], "Нулей нет нигде – удалены все столбцы"),
    _t([[0, 5, 1], [2, 0, 0]], "В каждом столбце есть нуль – удалений нет"),
    Test(["3 0", "2 2", "1 2", "0 -100", "0 -1"], ["n, m: 3 0 / 2 2", "строка 1: 1 2",
                                                  "строка 2: 0 -100 / 0 -1"],
         "Недопустимые данные: m = 0, элемент вне диапазона; удалён столбец 2"),
]

TASK = Task(
    part=1, num=2,
    statement="Дана целочисленная матрица A[1:n, 1:m]. Удалить путём сдвига все столбцы матрицы, "
              "не содержащие ни одного нуля.",
    short="Удаление столбцов без нулей",
    defines=IN.defines,
    decls=IN.decls + "    int q, t;\n",
    c_input=IN.c_input, c_solve=C_SOLVE, simulate=simulate,
    given=IN.given,
    result=["A[1:n, 1:q] – матрица после удаления столбцов, не содержащих нулей, где q – число оставшихся "
            "столбцов, или сообщение «Все столбцы не содержат нулей – удалены все столбцы, матрица пуста», или "
            "сообщение «В каждом столбце есть нуль – удалений не было, матрица не изменилась»."],
    when=IN.when, svyaz=svyaz, method=METHOD, spec=IN.spec + SPEC, pseudo=PSEUDO, tests=TESTS,
)
