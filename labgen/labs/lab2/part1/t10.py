from ..common import Task, Test
from ..inputs import MatrixArray
from .shared import c_find, py_find
from ....docx_engine import F

IN = MatrixArray("A", "B")

C_SOLVE = f'''    /* максимальный среди элементов A, которых нет в массиве B */
    found = 0;
    for (i = 1; i <= n; i++)
        for (j = 1; j <= m; j++){{
            {c_find("B", "k", "A[i][j]").replace(chr(10) + "        ", chr(10) + "            ")}
            if (t > k && (found == 0 || A[i][j] > mx)){{
                mx = A[i][j];
                found = 1;
            }}
        }}

    if (found == 0)
        printf("\\nВсе элементы матрицы встречаются в массиве B - "
               "искомого элемента нет.\\n");
    else
        printf("\\nМаксимальный среди элементов A, не встречающихся в B: %d\\n", mx);
'''


def simulate(con):
    n, m, A, k, B = IN.read(con)
    con.begin_results()
    vals = [A[i][j] for i in range(1, n + 1) for j in range(1, m + 1) if py_find(B, k, A[i][j]) > k]
    if not vals:
        con.printf("\nВсе элементы матрицы встречаются в массиве B - искомого элемента нет.\n")
    else:
        con.printf("\nМаксимальный среди элементов A, не встречающихся в B: %d\n" % max(vals))


def svyaz(rep):
    rep.fline("", F("mx = max { A[i, j] :  ∀ t = {1..k}: B[t] ≠ A[i, j] },  i = {1..n},  j = {1..m}"))


METHOD = [
    ("Для каждого элемента матрицы — поиск в массиве B (досрочный выход при совпадении); среди отсутствующих "
     "в B ищется максимальный (f – признак, что такой элемент уже встречался):",
     ["f = 0",
      ["для i = {1..n},  j = {1..m}",
       "t = 1",
       ["пока  t ≤ k  и  B[t] ≠ A[i, j]", "t = t + 1"],
       "(mx = A[i, j],  f = 1),  если  t > k  и  (f = 0  или  A[i, j] > mx)"]]),
]

SPEC = [
    ("label", "При found = 0"),
    ("box", ["Все элементы матрицы встречаются в массиве B - искомого элемента нет."], True),
    ("label", "Иначе"),
    ("box", ["Максимальный среди элементов A, не встречающихся в B: <<mx>>"], True),
]

PSEUDO = """
_алг_ «Лабораторная работа №2, часть I, задание 10»
_нач_
	ввод(n, m, A[1:n, 1:m], k, B[1:k])
	вывод(A[1:n, 1:m], B[1:k])
	found := 0
	_цикл_ _от_ i := 1 _до_ n
		_цикл_ _от_ j := 1 _до_ m
			t := 1
			_цикл-пока_ t ≤ k _и_ B[t] ≠ A[i, j]
				t := t + 1
			_кц_
			_если_ t > k _и_ (found = 0 _или_ A[i, j] > mx) _то_
				mx := A[i, j]; found := 1
			_всё_
		_кц_
	_кц_
	_если_ found = 0 _то_
		вывод(«Все элементы матрицы встречаются в массиве B - искомого элемента нет.»)
	_иначе_
		вывод(«Максимальный среди элементов A, не встречающихся в B: », mx)
	_всё_
_кон_
"""


def _t(mat, arr, case):
    return Test(IN.lines(mat, arr), IN.shown(mat, arr), case)


TESTS = [
    _t([[3, 9, -2], [7, 1, 9]], [9, 3], "Максимум A (9) есть в B – ответ 7"),
    _t([[-5, -1], [-8, -3]], [0], "Все элементы отрицательные и отсутствуют в B"),
    _t([[1, 2], [2, 1]], [1, 2, 3], "Все элементы есть в B – искомого нет"),
    Test(["1 1", "50", "1", "x50", "51"], ["n, m: 1 1", "A = 50", "k: 1", "B: x50 / 51"],
         "Недопустимые данные (буква перед числом); единственный элемент"),
]

TASK = Task(
    part=1, num=10,
    statement=("Даны целочисленная матрица A[1:n, 1:m] и целочисленный массив B[1:k]. Найти максимальный среди "
               "элементов матрицы A, не встречающихся в массиве B."),
    short="Максимальный элемент матрицы, отсутствующий в массиве",
    defines=IN.defines,
    decls=IN.decls + "    int t, mx = 0, found;\n",
    c_input=IN.c_input, c_solve=C_SOLVE, simulate=simulate,
    given=IN.given,
    result=["mx – максимальный среди элементов матрицы A, не встречающихся в массиве B, или сообщение «Все "
            "элементы матрицы встречаются в массиве B – искомого элемента нет»."],
    when=IN.when, svyaz=svyaz, method=METHOD, spec=IN.spec + SPEC, pseudo=PSEUDO, tests=TESTS,
)
