IN = MatrixArray("Z", "X")

C_SOLVE = f'''    /* в каждой строке - первый максимальный по модулю элемент и его поиск в X */
    cnt = 0;
    for (i = 1; i <= n; i++){{
        jm = 1;
        for (j = 2; j <= m; j++)
            if (ABS(Z[i][j]) > ABS(Z[i][jm])) jm = j;
        {c_find("X", "k", "Z[i][jm]")}
        if (t > k){{                       /* элемента нет в X - обнуляем */
            Z[i][jm] = 0;
            cnt++;
            row[cnt] = i;
        }}
    }}

    if (cnt == 0)
        printf("\\nМаксимальные по модулю элементы всех строк есть в массиве X - "
               "матрица не изменилась.\\n");
    else{{
{c_print_list("Обнулены максимальные по модулю элементы в строках: ", "row", "cnt")}
{c_print_mat("Z", "n", "m", "Преобразованная матрица Z:")}
    }}
'''


def simulate(con):
    n, m, Z, k, X = IN.read(con)
    con.begin_results()
    rows = []
    for i in range(1, n + 1):
        jm = 1
        for j in range(2, m + 1):
            if abs(Z[i][j]) > abs(Z[i][jm]):
                jm = j
        if py_find(X, k, Z[i][jm]) > k:
            Z[i][jm] = 0
            rows.append(i)
    if not rows:
        con.printf("\nМаксимальные по модулю элементы всех строк есть в массиве X - матрица не изменилась.\n")
    else:
        py_print_list(con, "Обнулены максимальные по модулю элементы в строках: ", rows)
        py_print_mat(con, Z, n, m, "Преобразованная матрица Z:")


def svyaz(rep):
    rep.fline("1. ", F("∀ i = {1..n}:  ∃ jm ∈ [1:m]:  ∀ j = {1..m}: |Z[i, j]| ≤ |Z[i, jm]|,"))
    rep.fline("", F("∀ j = {1..jm − 1}: |Z[i, j]| < |Z[i, jm]|"), indent=1.2)
    rep.fline("2. ", F("∀ i = {1..n}:  (∀ t = {1..k}: X[t] ≠ Z[i, jm])  ⇒  Z'[i, jm] = 0"))


