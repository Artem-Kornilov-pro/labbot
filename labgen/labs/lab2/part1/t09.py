from ..common import Task, Test
from ..inputs import MatrixArray
from .shared import c_print_mat, py_print_mat, mat_box
from ....docx_engine import F

IN = MatrixArray("A", "B")

C_SOLVE = f'''    /* максимальный элемент массива B */
    bm = B[1];
    for (t = 2; t <= k; t++)
        if (B[t] > bm) bm = B[t];
    /* удаление путём сдвига строк, содержащих элемент, равный bm */
    p = 0;                              /* число оставшихся строк */
    for (i = 1; i <= n; i++){{
        j = 1;
        while (j <= m && A[i][j] != bm)  /* досрочный выход при совпадении */
            j++;
        if (j > m){{                     /* совпадений нет - строка остаётся */
            p++;
            if (p != i)
                for (t = 1; t <= m; t++)
                    A[p][t] = A[i][t];
        }}
    }}

    printf("\\nМаксимальный элемент массива B: %d.\\n", bm);
    if (p == 0)
        printf("Каждая строка содержит этот элемент - удалены все строки, "
               "матрица пуста.\\n");
    else if (p == n)
        printf("Ни одна строка не содержит этот элемент - удалений не было, "
               "матрица не изменилась.\\n");
    else{{
        printf("Удалено строк: %d.\\n", n - p);
{c_print_mat("A", "p", "m", "Преобразованная матрица A:")}
    }}
'''


def simulate(con):
    n, m, A, k, B = IN.read(con)
    con.begin_results()
    bm = max(B[1:k + 1])
    p = 0
    for i in range(1, n + 1):
        if bm not in A[i][1:m + 1]:
            p += 1
            A[p] = list(A[i])
    con.printf("\nМаксимальный элемент массива B: %d.\n" % bm)
    if p == 0:
        con.printf("Каждая строка содержит этот элемент - удалены все строки, матрица пуста.\n")
    elif p == n:
        con.printf("Ни одна строка не содержит этот элемент - удалений не было, матрица не изменилась.\n")
    else:
        con.printf("Удалено строк: %d.\n" % (n - p))
        py_print_mat(con, A, p, m, "Преобразованная матрица A:")


def svyaz(rep):
    rep.fline("1. ", F("bm = max B[t],  t = {1..k}"))
    rep.fline("2. ", F("∀ i = {1..n}:  строка i удаляется  ⇔  ∃ j ∈ [1:m]: A[i, j] = bm"))
    rep.fline("", F("A'[1:p, 1:m] – оставшиеся строки в прежнем порядке"), indent=0.6)


