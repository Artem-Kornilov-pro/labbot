    _t([[5, 0], [1, 2], [3, 4]], "Первая с нулём выше последней без нулей: 1 ↔ 3"),
    _t([[1, 2], [3, 4]], "Нет строк с нулём – перестановка невозможна"),
    _t([[0, 1], [2, 0]], "Нет строк без нулей – перестановка невозможна"),
