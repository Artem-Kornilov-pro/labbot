IN = MatrixOnly("A")

C_SOLVE = f'''    /* первая строка, содержащая нуль (поиск сверху с досрочным выходом) */
    iz = 0;
    i = 1;
    while (i <= n && iz == 0){{
        j = 1;
        while (j <= m && A[i][j] != 0) j++;
        if (j <= m) iz = i;
        i++;
    }}
    /* последняя строка без нулей (поиск снизу с досрочным выходом) */
    inz = 0;
    i = n;
    while (i >= 1 && inz == 0){{
        j = 1;
        while (j <= m && A[i][j] != 0) j++;
        if (j > m) inz = i;
        i--;
    }}

    if (iz == 0)
        printf("\\nВ матрице нет строк, содержащих нулевой элемент - "
               "матрица не изменилась.\\n");
    else if (inz == 0)
        printf("\\nВ матрице нет строк без нулей - матрица не изменилась.\\n");
    else{{
        for (j = 1; j <= m; j++){{
            c = A[iz][j];
            A[iz][j] = A[inz][j];
            A[inz][j] = c;
        }}
        printf("\\nПереставлены строки %d и %d.\\n", iz, inz);
{c_print_mat("A", "n", "m", "Преобразованная матрица A:")}
    }}
'''


def simulate(con):
    n, m, A = IN.read(con)
    con.begin_results()
    has0 = [None] + [any(A[i][j] == 0 for j in range(1, m + 1)) for i in range(1, n + 1)]
    iz = next((i for i in range(1, n + 1) if has0[i]), 0)
    inz = next((i for i in range(n, 0, -1) if not has0[i]), 0)
    if iz == 0:
        con.printf("\nВ матрице нет строк, содержащих нулевой элемент - матрица не изменилась.\n")
    elif inz == 0:
        con.printf("\nВ матрице нет строк без нулей - матрица не изменилась.\n")
    else:
        A[iz], A[inz] = A[inz], A[iz]
        con.printf("\nПереставлены строки %d и %d.\n" % (iz, inz))
        py_print_mat(con, A, n, m, "Преобразованная матрица A:")


def svyaz(rep):
    rep.fline("1. ", F("∃ iz ∈ [1:n]:  (∃ j: A[iz, j] = 0)  и"))
    rep.fline("", F("∀ i = {1..iz − 1}, ∀ j = {1..m}: A[i, j] ≠ 0"), indent=0.6)
    rep.fline("2. ", F("∃ inz ∈ [1:n]:  (∀ j = {1..m}: A[inz, j] ≠ 0)  и"))
    rep.fline("", F("∀ i = {inz + 1..n}: ∃ j: A[i, j] = 0"), indent=0.6)
    rep.fline("3. ", F("∀ j = {1..m}:  A'[iz, j] = A[inz, j],  A'[inz, j] = A[iz, j]"))


