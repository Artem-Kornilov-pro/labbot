IN = MatrixArray("P", "Y")

C_SOLVE = r'''    /* для каждого столбца: произведение элементов и поиск его в массиве Y */
    cnt = 0;
    for (j = 1; j <= m; j++){
        pr = 1;
        i = 1;
        while (i <= n && pr != 0){        /* досрочный выход: при нуле pr уже 0 */
            pr = pr * P[i][j];
            i++;
        }
        t = 1;
        while (t <= k && Y[t] != pr)      /* досрочный выход при совпадении */
            t++;
        if (t > k){                       /* совпадений нет - сортируем столбец */
            cnt++;
            col[cnt] = j;
            p = n;
            sw = 1;
            while (sw){                   /* выход, если за проход не было обменов */
                sw = 0;
                for (i = 1; i < p; i++)
                    if (P[i][j] > P[i + 1][j]){
                        c = P[i][j];
                        P[i][j] = P[i + 1][j];
                        P[i + 1][j] = c;
                        sw = 1;
                    }
                p--;
            }
        }
    }

    if (cnt == 0)
        printf("\nПроизведение каждого столбца есть в массиве Y - "
               "матрица не изменилась.\n");
    else{
        printf("\nУпорядочены по возрастанию столбцы: ");
        for (t = 1; t <= cnt; t++)
            printf("%d ", col[t]);
        printf("\nПреобразованная матрица P:\n");
        for (i = 1; i <= n; i++){
            for (j = 1; j <= m; j++)
                printf("%5d", P[i][j]);
            printf("\n");
        }
    }
'''


def simulate(con):
    n, m_, P, k, Y = IN.read(con)
    con.begin_results()
    cols = []
    for j in range(1, m_ + 1):
        pr, i = 1, 1
        while i <= n and pr != 0:
            pr *= P[i][j]
            i += 1
        t = 1
        while t <= k and Y[t] != pr:
            t += 1
        if t > k:
            cols.append(j)
            col = sorted(P[i][j] for i in range(1, n + 1))
            for i in range(1, n + 1):
                P[i][j] = col[i - 1]
    if not cols:
        con.printf("\nПроизведение каждого столбца есть в массиве Y - матрица не изменилась.\n")
    else:
        con.printf("\nУпорядочены по возрастанию столбцы: " + "".join(f"{c} " for c in cols))
        py_print_matrix(con, P, n, m_, "\nПреобразованная матрица P:")


def svyaz(rep):
    rep.fline("1. ", F("∀ j = {1..m}:  pr[j] = ") + nprod(m("i = 1"), m("n"), m("P[i, j]")))
    rep.fline("2. ", F("∀ j = {1..m}:  (∀ t = {1..k}: Y[t] ≠ pr[j])  ⇒"))
    rep.fline("", F("⇒  ∀ i = {1..n − 1}:  P'[i, j] ≤ P'[i + 1, j],"), indent=0.6)
    rep.para("где P'[1:n, j] – тот же набор элементов столбца j, переставленный по возрастанию.", indent=0.6)


