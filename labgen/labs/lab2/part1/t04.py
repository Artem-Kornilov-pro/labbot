from ..common import Task, Test
from ..inputs import MatrixOnly
from .shared import c_print_mat, py_print_mat, mat_box
from ....docx_engine import F

IN = MatrixOnly("D")

C_SOLVE = f'''    /* удаление путём сдвига строк, содержащих только чётные элементы */
    p = 0;                              /* число оставшихся строк */
    for (i = 1; i <= n; i++){{
        j = 1;
        while (j <= m && D[i][j] % 2 == 0)  /* досрочный выход при нечётном */
            j++;
        if (j <= m){{                    /* есть нечётный элемент - строка остаётся */
            p++;
            if (p != i)
                for (t = 1; t <= m; t++)
                    D[p][t] = D[i][t];
        }}
    }}

    if (p == 0)
        printf("\\nВсе строки содержат только чётные элементы - удалены все строки, "
               "матрица пуста.\\n");
    else if (p == n)
        printf("\\nВ каждой строке есть нечётный элемент - удалений не было, "
               "матрица не изменилась.\\n");
    else{{
        printf("\\nУдалено строк: %d.\\n", n - p);
{c_print_mat("D", "p", "m", "Преобразованная матрица D:")}
    }}
'''


def simulate(con):
    n, m, D = IN.read(con)
    con.begin_results()
    p = 0
    for i in range(1, n + 1):
        j = 1
        while j <= m and D[i][j] % 2 == 0:
            j += 1
        if j <= m:
            p += 1
            D[p] = list(D[i])
    if p == 0:
        con.printf("\nВсе строки содержат только чётные элементы - удалены все строки, матрица пуста.\n")
    elif p == n:
        con.printf("\nВ каждой строке есть нечётный элемент - удалений не было, матрица не изменилась.\n")
    else:
        con.printf("\nУдалено строк: %d.\n" % (n - p))
        py_print_mat(con, D, p, m, "Преобразованная матрица D:")


def svyaz(rep):
    rep.fline("", F("∀ i = {1..n}:  строка i удаляется  ⇔  ∀ j = {1..m}: D[i, j] ⋮ 2"))
    rep.fline("", F("D'[1:p, 1:m] – оставшиеся строки в прежнем порядке"))


