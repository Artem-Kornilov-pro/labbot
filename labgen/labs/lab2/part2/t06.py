IN = PositiveArray()

C_SOLVE = r'''    /* суммы цифр в нечётных (s1) и чётных (s2) разрядах; разряды считаются справа */
    cnt = 0;
    for (i = 1; i <= n; i++){
        v = X[i];
        odd = 1;
        s1 = 0;
        s2 = 0;
        while (v > 0){
            if (odd) s1 = s1 + v % 10;
            else s2 = s2 + v % 10;
            odd = !odd;
            v = v / 10;
        }
        if (s1 == s2){
            cnt++;
            Y[cnt] = X[i];
        }
    }

    if (cnt == 0)
        printf("\nПодходящих элементов нет - новый массив пуст.\n");
    else{
        printf("\nНовый массив Y (%d эл.): ", cnt);
        for (i = 1; i <= cnt; i++)
            printf("%d ", Y[i]);
        printf("\n");
    }
'''


def digit_sums(x):
    s = [0, 0]
    odd = 1
    while x > 0:
        s[0 if odd else 1] += x % 10
        odd = 1 - odd
        x //= 10
    return s


def simulate(con):
    n, X = IN.read(con)
    con.begin_results()
    Y = [0] + [X[i] for i in range(1, n + 1) if digit_sums(X[i])[0] == digit_sums(X[i])[1]]
    if len(Y) == 1:
        con.printf("\nПодходящих элементов нет - новый массив пуст.\n")
    else:
        con.printf("\nНовый массив Y (%d эл.): " % (len(Y) - 1))
        py_print_array(con, Y, len(Y) - 1, "")


def svyaz(rep):
    rep.fline("", F("∀ i = {1..n}:  X[i] = ") + m("a[i, d[i]−1] … a[i, 1] a[i, 0]"))
    rep.para("(d[i] – число цифр, a[i, j] – цифра j-го разряда справа, j = 0 – единицы);", indent=0.6)
    rep.fline("", m("s1[i] = ") + nsum(m("j ⋮ 2"), m(""), m("a[i, j]")) + m(",   s2[i] = ")
              + nsum(m("j ⋮̸ 2"), m(""), m("a[i, j]")), indent=0.6)
    rep.fline("", F("Y[1:cnt]:  X[i] ∈ Y  ⇔  s1[i] = s2[i],  i = {1..n}"), indent=0.6)


